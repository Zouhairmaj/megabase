-- RLS fixtures for adversarial cases. auth.uid() already exists on the
-- reference database (the pinned Postgres image). The megabase database is
-- created empty, and prepare loads this file before Megabase installs Auth
-- SQL, so create the function only when it is missing. Do not replace the
-- reference body: auth.sql.function.uid compares it.
do $do$
begin
  if to_regprocedure('auth.uid()') is null then
    create schema if not exists auth;
    create function auth.uid()
    returns uuid
    language sql
    stable
    as $fn$
      select
      coalesce(
        nullif(current_setting('request.jwt.claim.sub', true), ''),
        (nullif(current_setting('request.jwt.claims', true), '')::jsonb ->> 'sub')
      )::uuid
    $fn$;
    grant execute on function auth.uid() to public;
  end if;
end
$do$;

-- Same guard for the other helpers the judge RPCs call. The reference
-- database already has them; the megabase database does not until Auth
-- starts and replaces these stubs. Do not replace a body that exists.
do $do$
begin
  if to_regprocedure('auth.jwt()') is null then
    create schema if not exists auth;
    create function auth.jwt()
    returns jsonb
    language sql
    stable
    as $fn$
      select
      coalesce(
        nullif(current_setting('request.jwt.claim', true), ''),
        nullif(current_setting('request.jwt.claims', true), '')
      )::jsonb
    $fn$;
    -- GoTrue's later migration replaces this body and must own the
    -- function. The reference init role (supabase_admin) can reassign
    -- it. `prepare` loads this file as `postgres`, which cannot, and
    -- Megabase replaces the stub itself.
    if exists (
      select 1
      from pg_roles
      where rolname = current_user
        and (rolsuper or pg_has_role(current_user, 'supabase_auth_admin', 'MEMBER'))
    ) then
      alter function auth.jwt() owner to supabase_auth_admin;
    end if;
    grant execute on function auth.jwt() to public;
  end if;
end
$do$;

