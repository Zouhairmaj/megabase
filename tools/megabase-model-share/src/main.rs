//! Attribute current tracked text lines to models; no network access is needed.

use std::collections::BTreeMap;
use std::path::{Path, PathBuf};
use std::process::Command;

use anyhow::{bail, Context, Result};
use serde::Serialize;

#[derive(Serialize)]
struct Report {
    generated_at_commit: String,
    total_lines: u64,
    models: Vec<ModelShare>,
}

#[derive(Serialize)]
struct ModelShare {
    model: String,
    lines: u64,
    share: f64,
}

// Only the final paragraph can be a trailer block. Do not attribute quoted
// examples in the subject/body, or ordinary author identities.
fn trailers(message: &str) -> Vec<(&str, &str)> {
    let message = message.trim_end();
    let block = message
        .rsplit_once("\n\n")
        .map_or(message, |(_, block)| block);
    let mut trailers = Vec::new();
    for line in block.lines() {
        if line.starts_with([' ', '\t']) && !trailers.is_empty() {
            continue;
        }
        let Some((key, value)) = line.split_once(':') else {
            return Vec::new();
        };
        if key.is_empty() || !key.bytes().all(|b| b.is_ascii_alphanumeric() || b == b'-') {
            return Vec::new();
        }
        trailers.push((key, value.trim()));
    }
    trailers
}

fn attribution(message: &str) -> String {
    let normalized = message.replace("\r\n", "\n");
    let trailers = trailers(&normalized);
    if let Some((_, model)) = trailers
        .iter()
        .rev()
        .find(|(key, value)| key.eq_ignore_ascii_case("Model") && !value.is_empty())
    {
        return model.to_ascii_lowercase();
    }
    for (key, value) in trailers {
        if key.eq_ignore_ascii_case("Co-authored-by") {
            let value = value.to_ascii_lowercase();
            for (identity, model) in [
                ("cursoragent", "cursor"),
                ("claude", "claude"),
                ("coderabbit", "coderabbit"),
                ("gemini", "gemini"),
                ("codex", "codex"),
            ] {
                if value.contains(identity) {
                    return model.to_owned();
                }
            }
        }
    }
    "unknown".to_owned()
}

fn excluded(path: &str) -> bool {
    path.split('/').any(|part| {
        matches!(
            part,
            "vendor" | "third_party" | "generated" | "target" | ".sqlx"
        )
    }) || path.starts_with("coverage/")
        || path.starts_with("docs/epics/")
        || path == "docs/backlog/PLAN.md"
        || path.rsplit('/').next().is_some_and(|name| {
            name.ends_with(".lock")
                || name.ends_with(".lockb")
                || name.ends_with(".lock.json")
                || name.ends_with("-lock.json")
                || name.ends_with("-lock.yaml")
                || name.ends_with(".min.js")
                || name.ends_with(".min.css")
                || name.ends_with(".map")
                || matches!(name, "go.sum" | "npm-shrinkwrap.json")
        })
}

fn eligible_text(bytes: &[u8]) -> bool {
    if bytes.contains(&0) {
        return false;
    }
    let Ok(text) = std::str::from_utf8(bytes) else {
        return false;
    };
    !text.lines().take(5).any(|line| {
        let line = line.to_ascii_lowercase();
        line.contains("@generated")
            || line.contains("auto-generated")
            || line.contains("automatically generated")
            || line.contains("generated by")
    })
}

/// Marker lines that open or close a generated `<!-- name:begin -->` region.
#[derive(Debug, PartialEq)]
enum Marker {
    Begin,
    End,
}

fn generated_marker(content: &str) -> Option<Marker> {
    let inner = content
        .trim()
        .strip_prefix("<!--")?
        .strip_suffix("-->")?
        .trim();
    if inner.ends_with(":begin") {
        Some(Marker::Begin)
    } else if inner.ends_with(":end") {
        Some(Marker::End)
    } else {
        None
    }
}

fn git(root: &Path, args: &[&str]) -> Result<Vec<u8>> {
    let output = Command::new("git").current_dir(root).args(args).output()?;
    if !output.status.success() {
        bail!(
            "git {} failed: {}",
            args[0],
            String::from_utf8_lossy(&output.stderr)
        );
    }
    Ok(output.stdout)
}

fn collect(root: &Path) -> Result<Report> {
    let generated_at_commit = String::from_utf8(git(root, &["rev-parse", "HEAD"])?)?
        .trim()
        .to_owned();
    let files = git(root, &["ls-files", "-z"])?;
    let mut commits = BTreeMap::<String, String>::new();
    let mut counts = BTreeMap::<String, u64>::new();
    for filename in files.split(|b| *b == 0).filter(|name| !name.is_empty()) {
        let filename = std::str::from_utf8(filename).context("non-UTF-8 tracked filename")?;
        if excluded(filename) {
            continue;
        }
        let path = root.join(filename);
        let metadata = match std::fs::symlink_metadata(&path) {
            Ok(metadata) => metadata,
            Err(error) if error.kind() == std::io::ErrorKind::NotFound => continue,
            Err(error) => return Err(error.into()),
        };
        if !metadata.is_file() || !eligible_text(&std::fs::read(&path)?) {
            continue;
        }
        let blame = git(root, &["blame", "--line-porcelain", "--", filename])
            .with_context(|| format!("blaming {filename}"))?;
        let mut commit = "";
        let mut in_generated = false;
        for line in std::str::from_utf8(&blame)?.lines() {
            // Header: object id, original line, final line, optional group size.
            let fields: Vec<_> = line.split_whitespace().collect();
            if matches!(fields.len(), 3 | 4)
                && matches!(fields[0].len(), 40 | 64)
                && fields[0].bytes().all(|b| b.is_ascii_hexdigit())
                && fields[1].parse::<u64>().is_ok()
                && fields[2].parse::<u64>().is_ok()
                && !line.starts_with('\t')
            {
                commit = fields[0];
            } else if let Some(content) = line.strip_prefix('\t') {
                // Skip generated `<!-- x:begin -->`..`<!-- x:end -->` regions,
                // markers included.
                match generated_marker(content) {
                    Some(Marker::Begin) => in_generated = true,
                    Some(Marker::End) => {
                        in_generated = false;
                        continue;
                    }
                    None => {}
                }
                if in_generated {
                    continue;
                }
                if commit.is_empty() {
                    bail!("missing blame header for {filename}");
                }
                if !commits.contains_key(commit) {
                    let model = if commit.bytes().all(|b| b == b'0') {
                        "unknown".to_owned()
                    } else {
                        let message = git(root, &["show", "-s", "--format=%B", commit])?;
                        attribution(&String::from_utf8_lossy(&message))
                    };
                    commits.insert(commit.to_owned(), model);
                }
                *counts.entry(commits[commit].clone()).or_default() += 1;
            }
        }
    }
    let total_lines = counts.values().sum();
    let mut models: Vec<_> = counts
        .into_iter()
        .map(|(model, lines)| ModelShare {
            model,
            lines,
            share: if total_lines == 0 {
                0.0
            } else {
                lines as f64 / total_lines as f64
            },
        })
        .collect();
    models.sort_by(|a, b| b.lines.cmp(&a.lines).then_with(|| a.model.cmp(&b.model)));
    Ok(Report {
        generated_at_commit,
        total_lines,
        models,
    })
}

fn main() -> Result<()> {
    let mut args = std::env::args_os().skip(1);
    let out = match args.next() {
        None => None,
        Some(arg) if arg == "--out" => {
            Some(PathBuf::from(args.next().context("--out requires a path")?))
        }
        Some(arg) if arg == "--help" || arg == "-h" => {
            println!("Usage: megabase-model-share [--out <path>]");
            return Ok(());
        }
        Some(_) => bail!("usage: megabase-model-share [--out <path>]"),
    };
    if args.next().is_some() {
        bail!("usage: megabase-model-share [--out <path>]");
    }
    let cwd = std::env::current_dir()?;
    let root = String::from_utf8(git(&cwd, &["rev-parse", "--show-toplevel"])?)?;
    let report = collect(Path::new(root.trim_end()))?;
    let mut json = serde_json::to_string_pretty(&report)?;
    json.push('\n');
    if let Some(path) = out {
        std::fs::write(path, json)?;
    } else {
        use std::io::Write;
        std::io::stdout().lock().write_all(json.as_bytes())?;
    }
    Ok(())
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn explicit_model_wins_and_last_nonempty_value_wins() {
        assert_eq!(attribution("subject\n\nModel: old\nCo-authored-by: Claude <bot@example.test>\nMODEL: GPT-6\nModel: "), "gpt-6");
    }

    #[test]
    fn recognizes_all_coauthors_case_insensitively() {
        for (name, expected) in [
            ("CursorAgent", "cursor"),
            ("CLAUDE", "claude"),
            ("CodeRabbit", "coderabbit"),
            ("Gemini", "gemini"),
            ("Codex", "codex"),
        ] {
            assert_eq!(
                attribution(&format!(
                    "subject\n\nco-AUTHORED-by: {name} <bot@example.test>"
                )),
                expected
            );
        }
    }

    #[test]
    fn ignores_body_examples_and_unknown_authors() {
        for message in [
            "",
            "Model: codex\n\nordinary body",
            "subject\n\nModel: claude\nthis is prose",
            "subject\n\nCo-authored-by: Human <human@example.test>",
        ] {
            assert_eq!(attribution(message), "unknown");
        }
    }

    #[test]
    fn handles_crlf_and_multiple_coauthors() {
        assert_eq!(attribution("subject\r\n\r\nCo-authored-by: Human <h@example.test>\r\nCo-authored-by: CODEX <c@example.test>\r\n"), "codex");
        assert_eq!(
            attribution("subject\n\nModel:\nCo-authored-by: Gemini <g@example.test>"),
            "gemini"
        );
    }

    #[test]
    fn detects_generated_region_markers() {
        assert_eq!(
            generated_marker("<!-- status:begin -->"),
            Some(Marker::Begin)
        );
        assert_eq!(generated_marker("  <!-- pins:end -->"), Some(Marker::End));
        assert_eq!(generated_marker("<!-- just a comment -->"), None);
        assert_eq!(generated_marker("text"), None);
    }

    #[test]
    fn filters_generated_binary_and_lockfiles() {
        for path in [
            "vendor/auth/a.rs",
            "third_party/a.rs",
            "coverage/a.json",
            ".sqlx/query.json",
            "docs/epics/auth.md",
            "docs/backlog/PLAN.md",
            "site/Cargo.lock",
            "package-lock.json",
            "pnpm-lock.yaml",
            "bun.lockb",
            "a/generated/file.rs",
        ] {
            assert!(excluded(path), "{path}");
        }
        assert!(!excluded("crates/core/src/lib.rs"));
        assert!(!eligible_text(b"binary\0data"));
        assert!(!eligible_text(b"\xff\xfe"));
        assert!(!eligible_text(b"// @generated\nfn main() {}"));
        assert!(eligible_text(b"// A comment\nfn main() {}\n"));
    }
}
